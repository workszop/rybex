// Wraps the vendored Three.js ES module (r170) and RoundedBoxGeometry into one classic script that sets window.THREE,
// because <script type="module"> does not load from file:// and the app must keep working opened from disk.
// Usage: node tools/build-three-global.mjs [--check]   (--check exits 1 when vendor/three/three.global.js is stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'vendor', 'three');
const OUT = path.join(DIR, 'three.global.js');

function build() {
  const core = fs.readFileSync(path.join(DIR, 'three.module.min.js'), 'utf8');
  // The minified module ends with a single export list: export{a as B,c as D,...};
  const m = core.match(/export\s*\{([^}]*)\}\s*;?\s*$/);
  if (!m) throw new Error('three.module.min.js: trailing export{...} not found');
  if ((core.match(/\bexport\s*\{/g) || []).length !== 1) throw new Error('three.module.min.js: expected exactly one export list');
  if (/(^|[;}\s])import\s*(\{|\*|\(|[\w$]+\s+from\b)/.test(core.slice(0, m.index))) throw new Error('three.module.min.js: unexpected import statement');
  const pairs = m[1].split(',').map(s => s.trim()).filter(Boolean).map(s => {
    const p = s.split(/\s+as\s+/);
    if (p.length > 2 || !/^[\w$]+$/.test(p[0]) || (p[1] && !/^[\w$]+$/.test(p[1]))) throw new Error(`three.module.min.js: odd export "${s}"`);
    return [p[0], p[1] || p[0]];
  });
  const body = core.slice(0, m.index);
  const ns = '{' + pairs.map(([local, name]) => `${name}:${local}`).join(',') + '}';

  const rb = fs.readFileSync(path.join(DIR, 'RoundedBoxGeometry.js'), 'utf8');
  const imp = rb.match(/import\s*\{([^}]*)\}\s*from\s*['"]three['"]\s*;?/);
  const exp = rb.match(/export\s*\{\s*RoundedBoxGeometry\s*\}\s*;?/);
  if (!imp || !exp) throw new Error('RoundedBoxGeometry.js: expected import {...} from \'three\' and export { RoundedBoxGeometry }');
  const names = imp[1].split(',').map(s => s.trim()).filter(Boolean);
  const rbBody = rb.replace(imp[0], `const { ${names.join(', ')} } = THREE;`).replace(exp[0], 'return RoundedBoxGeometry;');

  return '// Generated by tools/build-three-global.mjs from three.module.min.js (r170) and RoundedBoxGeometry.js. Do not edit; rerun the script.\n'
    + '(function(){"use strict";\n'
    + 'var THREE=(function(){\n' + body + '\nreturn ' + ns + ';\n})();\n'
    + 'THREE.RoundedBoxGeometry=(function(THREE){\n' + rbBody + '\n})(THREE);\n'
    + 'window.THREE=THREE;\n})();\n';
}

const out = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== out) { console.error(`${path.relative(process.cwd(), OUT)} is stale: rerun node tools/build-three-global.mjs`); process.exit(1); }
  console.log(`${path.relative(process.cwd(), OUT)} is up to date`);
} else {
  fs.writeFileSync(OUT, out);
  console.log(`${path.relative(process.cwd(), OUT)}: ${(out.length / 1e3).toFixed(0)} kB`);
}
