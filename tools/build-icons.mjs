// Builds vendor/icons.js: only the lucide icons the app names, inlined, so the page needs no icon CDN (~81 KB gzipped).
// Usage: node tools/build-icons.mjs   (needs network once, to read lucide's UMD build; node 18+)
// An icon counts as used when its kebab-case name appears as a quoted string in rybex-ai-workshop.html or js/*.js (a superset:
// a few common words match too, which costs a few hundred bytes). After adding a new icon name to the app, rerun this.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const VERSION = '1.57.0';
const code = await (await fetch(`https://cdn.jsdelivr.net/npm/lucide@${VERSION}/dist/umd/lucide.min.js`)).text();
const sandbox = { self: {}, window: {}, document: {}, console };
sandbox.globalThis = sandbox;
vm.runInNewContext(code, sandbox);
const lucide = sandbox.lucide || sandbox.self.lucide || sandbox.window.lucide;
if (!lucide || !lucide.icons) throw new Error('lucide.icons not found in the UMD build');

const src = ['rybex-ai-workshop.html', ...fs.readdirSync(path.join(ROOT, 'js')).map(f => 'js/' + f)].map(f => fs.readFileSync(path.join(ROOT, f), 'utf8')).join('\n');
const kebab = n => n.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Za-z])([0-9])/g, '$1-$2').toLowerCase();
const attr = a => Object.entries(a).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ');
const used = {};
for (const [name, nodes] of Object.entries(lucide.icons)) {
  const n = kebab(name);
  if (new RegExp('[\'"`]' + n.replace(/-/g, '\\-') + '[\'"`]').test(src)) used[n] = nodes.map(([t, a]) => `<${t} ${attr(a)}/>`).join('');
}
const named = new Set([...src.matchAll(/data-lucide="([a-z0-9-]+)"|\bic\('([a-z0-9-]+)'/g)].map(m => m[1] || m[2]));
const missing = [...named].filter(n => !used[n]);
if (missing.length) throw new Error('icons named in the app but not in lucide ' + VERSION + ': ' + missing.join(', '));

const body = Object.keys(used).sort().map(n => `${JSON.stringify(n)}:${JSON.stringify(used[n])}`).join(',\n');
fs.writeFileSync(path.join(ROOT, 'vendor', 'icons.js'),
  `// lucide ${VERSION} (ISC licence), the icons the app names. Generated by tools/build-icons.mjs; do not edit.\n` +
  `window.ICONS={\n${body}\n};\n`);
console.log('vendor/icons.js:', Object.keys(used).length, 'icons');
